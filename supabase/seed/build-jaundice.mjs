// Rebuilds supabase/seed/approach-jaundice.sql from the reviewed content in supabase/seed/content/.
// Run from the project folder after editing that content:  node supabase/seed/build-jaundice.mjs
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const out = join(mkdtempSync(join(tmpdir(), 'seed-')), 'case.cjs');
await build({ entryPoints: ['supabase/seed/content/jaundice-painless.ts'], bundle: true, format: 'cjs', platform: 'node', outfile: out, logLevel: 'error' });
const c = createRequire(import.meta.url)(out).jaundicePainless;
const sheet = readFileSync('supabase/seed/content/jaundice.md', 'utf8');
const json = JSON.stringify(c);
if (sheet.includes('$sheet$') || json.includes('$case$')) throw new Error('A dollar-quote delimiter appears in the content.');
const q = (s) => s.replace(/'/g, "''");
const summary = 'Confirm it, look for danger, fractionate the bilirubin, read the enzyme pattern, then image the ducts.';
const D = '$';

const sql = `-- ════════════════════════════════════════════════════════════════════════════════════════════
--  The Clinical Room · seed: the jaundice approach (Medicine) and its first case, Case ${c.number}
--
--  Run in Supabase → SQL Editor after migration 20261111000007_approaches_and_cases.sql.
--  Both rows go in as DRAFTS: only admins see them on the site, so you can check them live first.
--  When you're happy, run the two lines in step 2 at the bottom to publish them to approved students.
--  Running this file again updates the rows in place (it never duplicates them or changes their status).
--  Generated by supabase/seed/build-jaundice.mjs from supabase/seed/content/; edit those, not this.
-- ════════════════════════════════════════════════════════════════════════════════════════════

-- ── step 1: add (or refresh) the approach and the case, as drafts ──

insert into public.approaches (specialty_id, id, title, summary, sheet, sort, access, status)
values ('medicine', 'jaundice', 'Jaundice', '${q(summary)}', ${D}sheet${D}${sheet}${D}sheet${D}, 0, 'approved', 'draft')
on conflict (specialty_id, id) do update
  set title = excluded.title, summary = excluded.summary, sheet = excluded.sheet;

insert into public.cases (specialty_id, id, approach_id, number, title, data, sort, access, status)
values ('medicine', '${c.id}', '${c.approachId}', '${c.number}', '${q(c.title)}', ${D}case${D}${json}${D}case${D}::jsonb, 0, 'approved', 'draft')
on conflict (specialty_id, id) do update
  set approach_id = excluded.approach_id, number = excluded.number, title = excluded.title, data = excluded.data;


-- ── step 2: publish (run these two lines only when you're ready for students to see them) ──

-- update public.approaches set status = 'published' where specialty_id = 'medicine' and id = 'jaundice';
-- update public.cases      set status = 'published' where specialty_id = 'medicine' and id = '${c.id}';
`;
writeFileSync('supabase/seed/approach-jaundice.sql', sql);
console.log('Wrote supabase/seed/approach-jaundice.sql');
