// Builds the "frequently asked in OSCE finals" Surgery questions, for review and import.
//
// Reads  supabase/seed/content/surgery-finals-{1,2,3}.mjs   (the written answers; git-ignored, protected)
// Writes src/dev/surgery-preview.json                        (adds them to the dev preview, ?preview-bank=1; git-ignored)
//        supabase/seed/content/surgery-finals-review.md      (every question by topic, for review; git-ignored)
//        supabase/seed/surgery-finals-import.sql             (the import, as drafts; git-ignored)
//
// Each question's source is "Frequently asked in OSCE finals", which shows the small gold star on the site.
// Run: node supabase/seed/build-surgery-finals.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { PART1 } from './content/surgery-finals-1.mjs';
import { PART2 } from './content/surgery-finals-2.mjs';
import { PART3 } from './content/surgery-finals-3.mjs';

const SOURCE = 'Frequently asked in OSCE finals';

// three small topics these questions need that Surgery doesn't have yet
const NEW_TOPICS = [
  { id: 'sx-upper-gi', name: 'Stomach and duodenum', subjectId: 'abdomen', sort: 60 },
  { id: 'sx-exam-skills', name: 'Examination skills', subjectId: 'principles', sort: 60 },
  { id: 'sx-ent', name: 'Epistaxis', subjectId: 'thyroid', sort: 60 },
];

const KNOWN_TOPICS = new Set([
  'appendix', 'gallbladder-biliary-tract', 'intestinal-obstruction',
  'sx-acute-abdomen', 'sx-jaundice-liver', 'sx-pancreas', 'sx-goitre', 'sx-thyroidectomy', 'sx-neck-lumps',
  'sx-breast-cancer', 'sx-hernia', 'sx-anorectal', 'sx-wounds', 'sx-periop', 'sx-bleeding-drains', 'sx-splenectomy',
  'sx-diabetic-foot', 'sx-joints', 'sx-abdo-trauma', 'sx-chest-trauma', 'sx-head-injury', 'sx-abdo-masses',
  'sx-vascular-exam', 'sx-imaging', 'sx-diverticular',
  ...NEW_TOPICS.map((t) => t.id),
]);

const all = [...PART1, ...PART2, ...PART3];
const seen = new Set();
const questions = all.map(([id, topicId, difficulty, title, answer, rows], i) => {
  if (seen.has(id)) throw new Error(`Duplicate id ${id}`);
  seen.add(id);
  if (!KNOWN_TOPICS.has(topicId)) throw new Error(`${id}: unknown topic ${topicId}`);
  if (/ · /.test(answer)) throw new Error(`${id}: dot-separated list`);
  const open = (answer.match(/^:::\w+/gm) ?? []).length;
  const close = (answer.match(/^:::$/gm) ?? []).length;
  if (open !== close) throw new Error(`${id}: unbalanced boxes`);
  let cols = null;
  answer.split('\n').forEach((l, n) => {
    if (!l.startsWith('|')) return void (cols = null);
    const c = l.split('|').length;
    if (cols === null) cols = c;
    else if (c !== cols) throw new Error(`${id}: table columns differ on line ${n + 1}`);
  });
  return { id, title, type: 'viva', topicIds: [topicId], doctorIds: [], modelAnswer: answer.trim(), difficulty, source: SOURCE, _rows: rows, _sort: 900 + i };
});

/* ───────────── dev preview: add to the Surgery bank preview ───────────── */

const previewPath = 'src/dev/surgery-preview.json';
const preview = JSON.parse(readFileSync(previewPath, 'utf8'));
preview.questions = preview.questions.filter((q) => !q.id.startsWith('sx-f')).concat(questions.map(({ _rows, _sort, ...q }) => q));
preview.topics = preview.topics.filter((t) => !NEW_TOPICS.some((n) => n.id === t.id)).concat(NEW_TOPICS.map(({ sort, ...t }) => t));
writeFileSync(previewPath, JSON.stringify(preview, null, 1));

/* ───────────── review sheet ───────────── */

let md = `# Surgery: frequently asked OSCE finals questions (review)\n\n${questions.length} new questions from \`General_Surgery_OSCE_Extraction.xlsx\`, written from standard surgical teaching and UK guidance. Each carries the gold "Finals" star. Imported as drafts.\n\n`;
const byTopic = new Map();
for (const q of questions) (byTopic.get(q.topicIds[0]) ?? byTopic.set(q.topicIds[0], []).get(q.topicIds[0])).push(q);
for (const [t, list] of byTopic) md += `## ${t}\n\n` + list.map((q) => `- **${q.id}** ${q.title} _(from ${q._rows.join(', ')})_`).join('\n') + '\n\n';
writeFileSync('supabase/seed/content/surgery-finals-review.md', md);

/* ───────────── import (drafts) ───────────── */

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
let sql = `-- The Clinical Room · Surgery "frequently asked in OSCE finals" questions (generated by build-surgery-finals.mjs; git-ignored)\n-- Imports ${questions.length} questions as DRAFTS, with ${NEW_TOPICS.length} new topics. Safe to run again.\n\nbegin;\n\n`;
sql += `insert into public.topics (specialty_id, id, name, subject_id, sort) values\n` + NEW_TOPICS.map((t) => `  ('surgery', ${sq(t.id)}, ${sq(t.name)}, ${sq(t.subjectId)}, ${t.sort})`).join(',\n') + `\non conflict (specialty_id, id) do update set name = excluded.name, subject_id = excluded.subject_id;\n\n`;
sql += `insert into public.questions (specialty_id, id, title, type, model_answer, difficulty, source, status, sort) values\n` + questions.map((q) => `  ('surgery', ${sq(q.id)}, ${sq(q.title)}, 'viva', ${sq(q.modelAnswer)}, ${q.difficulty}, ${sq(SOURCE)}, 'draft', ${q._sort})`).join(',\n') + `\non conflict (specialty_id, id) do update set title = excluded.title, model_answer = excluded.model_answer, difficulty = excluded.difficulty, source = excluded.source;\n\n`;
sql += `insert into public.question_topics (specialty_id, question_id, topic_id) values\n` + questions.map((q) => `  ('surgery', ${sq(q.id)}, ${sq(q.topicIds[0])})`).join(',\n') + `\non conflict do nothing;\n\ncommit;\n\nselect status, count(*) from public.questions where specialty_id = 'surgery' and source = ${sq(SOURCE)} group by status;\n`;
writeFileSync('supabase/seed/surgery-finals-import.sql', sql);

console.log(JSON.stringify({ questions: questions.length, topics: byTopic.size, newTopics: NEW_TOPICS.length, easy: questions.filter((q) => q.difficulty === 1).length, moderate: questions.filter((q) => q.difficulty === 2).length, difficult: questions.filter((q) => q.difficulty === 3).length }));
