// Adds the scores and criteria questions to the Medicine and Surgery banks.
//
// Reads  supabase/seed/content/scores.mjs           (the questions and links; git-ignored, protected)
// Adds   them to src/dev/{medicine,surgery}-preview.json (dev-only preview; run after the bank builds)
// Writes supabase/seed/scores-import.sql             (the import, new questions as drafts; git-ignored)
//
// Each question is written once and filed in two topics: its own topic and a "Scores and criteria"
// list. Existing score questions are linked into the list unchanged.
// Run: node supabase/seed/build-medicine.mjs && node supabase/seed/build-surgery.mjs && node supabase/seed/build-scores.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { LINKS, QUESTIONS, SUBJECTS, TOPICS } from './content/scores.mjs';

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const previews = {
  medicine: JSON.parse(readFileSync('src/dev/medicine-preview.json', 'utf8')),
  surgery: JSON.parse(readFileSync('src/dev/surgery-preview.json', 'utf8')),
};

// the Medicine GCS question shares the Surgery answer (one specialty can't show another's question)
const gcs = previews.surgery.questions.find((q) => q.id === 'sx-q027')?.modelAnswer;
if (!gcs) throw new Error('The Surgery GCS answer (sx-q027) is missing from the preview');

let sql = `-- The Clinical Room · scores and criteria (generated by build-scores.mjs; git-ignored)\n-- New questions go in as DRAFTS; existing questions are only added to the new lists. Safe to run again.\n\nbegin;\n\n`;
const counts = {};

for (const sp of ['medicine', 'surgery']) {
  const p = previews[sp];
  const subject = SUBJECTS[sp];
  const scoreTopics = new Set(TOPICS[sp].map(([id]) => id));

  // preview: the subject, its topics, the new questions and the links (idempotent)
  p.subjects = [...(p.subjects ?? []).filter((s) => s.id !== subject.id), { id: subject.id, name: subject.name }];
  p.topics = [...p.topics.filter((t) => !scoreTopics.has(t.id)), ...TOPICS[sp].map(([id, name]) => ({ id, name, subjectId: subject.id }))];
  const fresh = QUESTIONS[sp].map(([id, home, list, difficulty, title, answer]) => ({ id, title, type: 'viva', topicIds: [home, list], doctorIds: [], modelAnswer: answer ?? gcs, difficulty }));
  const freshIds = new Set(fresh.map((q) => q.id));
  p.questions = [...p.questions.filter((q) => !freshIds.has(q.id)), ...fresh];
  for (const [qid, topic] of Object.entries(LINKS[sp])) {
    const q = p.questions.find((x) => x.id === qid);
    if (q && !q.topicIds.includes(topic)) q.topicIds.push(topic);
  }

  // the import
  sql += `-- ${sp}\ninsert into public.subjects (specialty_id, id, name, sort) values (${sq(sp)}, ${sq(subject.id)}, ${sq(subject.name)}, ${subject.sort})\non conflict (specialty_id, id) do update set name = excluded.name;\n\n`;
  sql += `insert into public.topics (specialty_id, id, name, subject_id, sort) values\n` + TOPICS[sp].map(([id, name], i) => `  (${sq(sp)}, ${sq(id)}, ${sq(name)}, ${sq(subject.id)}, ${i + 1})`).join(',\n') + `\non conflict (specialty_id, id) do update set name = excluded.name, subject_id = excluded.subject_id, sort = excluded.sort;\n\n`;
  sql += `insert into public.questions (specialty_id, id, title, type, model_answer, difficulty, status, sort) values\n` + fresh.map((q, i) => `  (${sq(sp)}, ${sq(q.id)}, ${sq(q.title)}, 'viva', ${sq(q.modelAnswer)}, ${q.difficulty}, 'draft', ${2000 + i})`).join(',\n') + `\non conflict (specialty_id, id) do update set title = excluded.title, model_answer = excluded.model_answer, difficulty = excluded.difficulty;\n\n`;
  const rows = [...fresh.flatMap((q) => q.topicIds.map((t) => [q.id, t])), ...Object.entries(LINKS[sp])];
  sql += `insert into public.question_topics (specialty_id, question_id, topic_id) values\n` + rows.map(([q, t]) => `  (${sq(sp)}, ${sq(q)}, ${sq(t)})`).join(',\n') + `\non conflict do nothing;\n\n`;
  counts[sp] = { new: fresh.length, linked: Object.keys(LINKS[sp]).length, topics: TOPICS[sp].length };
}

sql += `commit;\n\nselect t.specialty_id, t.name, count(qt.question_id) as questions\nfrom public.topics t left join public.question_topics qt on qt.specialty_id = t.specialty_id and qt.topic_id = t.id\nwhere t.subject_id = 'scores' group by t.specialty_id, t.name, t.sort order by t.specialty_id, t.sort;\n`;

writeFileSync('src/dev/medicine-preview.json', JSON.stringify(previews.medicine, null, 1));
writeFileSync('src/dev/surgery-preview.json', JSON.stringify(previews.surgery, null, 1));
writeFileSync('supabase/seed/scores-import.sql', sql);
console.log(JSON.stringify(counts));
