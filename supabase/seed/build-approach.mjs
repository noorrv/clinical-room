// Writes the import for one written approach from its sheet in supabase/seed/content/.
//
//   node supabase/seed/build-approach.mjs <specialty> <id> <sheet file> "<title>" "<one-line summary>"
//   e.g. node supabase/seed/build-approach.mjs paediatrics dehydration dehydration.md "Dehydration in children" "Shock first, ..."
//
// Writes supabase/seed/approach-<id>.sql (git-ignored). The approach goes in as a DRAFT: admins see it
// on the site, students don't, until it is published. Running it again updates the row in place.

import { readFileSync, writeFileSync } from 'node:fs';

const [specialty, id, file, title, summary] = process.argv.slice(2);
if (!summary) throw new Error('Usage: build-approach.mjs <specialty> <id> <sheet file> "<title>" "<summary>"');
const sheet = readFileSync(`supabase/seed/content/${file}`, 'utf8').trim();
if (sheet.includes('$sheet$')) throw new Error('The sheet contains the $sheet$ delimiter.');
const q = (s) => `'${s.replace(/'/g, "''")}'`;

const sql = `-- The Clinical Room · the "${title}" approach (${specialty}), generated by build-approach.mjs (git-ignored)
-- Goes in as a DRAFT (admins only). Running it again updates the text and keeps its status.

insert into public.approaches (specialty_id, id, title, summary, sheet, sort, access, status)
values (${q(specialty)}, ${q(id)}, ${q(title)}, ${q(summary)}, $sheet$${sheet}$sheet$, 0, 'approved', 'draft')
on conflict (specialty_id, id) do update set title = excluded.title, summary = excluded.summary, sheet = excluded.sheet;

select specialty_id, id, title, status, length(sheet) as characters from public.approaches where specialty_id = ${q(specialty)} and id = ${q(id)};

-- To publish it to approved students once checked:
-- update public.approaches set status = 'published' where specialty_id = ${q(specialty)} and id = ${q(id)};
`;
writeFileSync(`supabase/seed/approach-${id}.sql`, sql);
console.log(JSON.stringify({ specialty, id, sections: (sheet.match(/^## /gm) ?? []).length, characters: sheet.length }));
